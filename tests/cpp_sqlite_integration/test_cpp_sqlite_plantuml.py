class TestClassScopedView:
    """Verify the ``scope_class`` PlantUML export produces a
    class-centric dependency view.

    When scoped to ``cpp_sqlite::Database``:
    - Database shows ALL members (including private) in full detail.
    - Dependent classes (Transaction, DataAccessObject, DAOBase)
      only show the specific members Database calls.
    - External dependencies (std, boost, spdlog, sqlite3) are
      collapsed into packages.
    - File nodes and concept nodes are omitted.
    """

    @classmethod
    @pytest.fixture(scope="class")
    def scoped_database_puml(cls):
        """Generate the scoped PlantUML for Database on the fly."""
        import json as _json
        from codegraph.graph import LayerGraph
        from codegraph.export.plantuml import PlantUMLExporter

        json_path = _UNIT_TEST_DATA / "cpp_sqlite_one_hop.json"
        data = _json.loads(json_path.read_text(encoding="utf-8"))
        graph = LayerGraph.deserialize(data)
        return PlantUMLExporter(
            graph, fields="all", scope_class="cpp_sqlite::Database"
        ).export()

    # ------------------------------------------------------------------
    # Target class assertions
    # ------------------------------------------------------------------

    def test_database_shows_all_members(self, scoped_database_puml):
        """Database is rendered as a package with each member as a
        standalone ``class <<method>>`` or ``class <<attribute>>`` node."""
        assert 'package "Database" as cpp_sqlite__Database' in scoped_database_puml
        for member_name in (
            "select", "withTransaction", "getDAO", "getRawDB",
            "flushAllDAOs", "insert", "isInTransaction",
            "Database",  # constructor
            "daos_", "daoCreationOrder_", "pLogger_", "db_",
        ):
            # The alias uses _sanitize_alias which strips trailing _
            from codegraph.export.plantuml import _sanitize_alias
            safe = _sanitize_alias(member_name)
            assert f'class "{member_name}" as cpp_sqlite__Database__{safe}' in scoped_database_puml, (
                f"Database member {member_name} missing from scoped view"
            )
            # Verify stereotype: methods get <<method>>, attributes get <<attribute>>
            if member_name in ("daos_", "daoCreationOrder_", "pLogger_", "db_"):
                assert "<<attribute>>" in scoped_database_puml
            else:
                assert "<<method>>" in scoped_database_puml

    def test_database_rendered_as_package(self, scoped_database_puml):
        """The scoped class is a ``package`` container, not a ``class``."""
        assert 'package "Database" as cpp_sqlite__Database {' in scoped_database_puml

    def test_transaction_only_shows_commit(self, scoped_database_puml):
        """Transaction class only exposes ``commit()`` — the only
        method Database actually calls."""
        assert "commit()" in scoped_database_puml
        for hidden in ("executeSQL", "rollback", "getSavepointName",
                       "isActive", "isActive_", "savepointName_"):
            assert hidden not in scoped_database_puml, (
                f"Transaction member {hidden} should not appear in scoped view"
            )

    def test_data_access_object_no_members(self, scoped_database_puml):
        """DataAccessObject appears (Database DEPENDS_ON it) but with
        no members — Database doesn't invoke specific methods."""
        assert "DataAccessObject" in scoped_database_puml
        for hidden in ("prepareSelectStatements", "selectCacheById",
                       "selectAll", "prepareSQLStatements",
                       "generateSelectAllSQL", "generateInsertSQL",
                       "getTableName", "generateCreateTableSQL",
                       "incrementIdCounter", "executeCreateStmt",
                       "addToBuffer"):
            assert hidden not in scoped_database_puml, (
                f"DataAccessObject member {hidden} should not appear"
            )

