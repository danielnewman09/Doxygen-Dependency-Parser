    def test_no_private_member_lines(self, public_puml):
        """No private member lines (``-`` prefix) appear in the
        public-only view."""
        for line in public_puml.splitlines():
            stripped = line.strip()
            if stripped and stripped[0] == "-":
                # Allow ``-`` in arrow symbols like <|-- and -->
                if "<|" in stripped or "--" in stripped:
                    continue
                raise AssertionError(
                    f"Private member line found in public view: {line.strip()!r}"
                )

    def test_public_view_has_no_private_members_in_classes(self, public_puml):
        """Class bodies in the public view contain only public/protected
        members (``+`` or ``#`` prefix), never private (``-``) members."""
        # Extract all member lines: lines starting with +, -, or # after
        # whitespace (inside class/enum/package bodies).
        member_lines = [
            L.strip() for L in public_puml.splitlines()
            if L.strip() and L.strip()[0] in ("+", "-", "#")
        ]
        private_lines = [L for L in member_lines if L[0] == "-"]
        assert len(private_lines) == 0, (
            f"Found {len(private_lines)} private member lines in public view:\n"
            + "\n".join(f"  {L}" for L in private_lines[:10])
        )

    def test_no_member_aliases_as_arrow_targets(self, public_puml):
        """No arrow target should be a member alias.

        The check is structural: every arrow target must be an alias
        declared as a standalone element (class, interface, enum,
        union, package, or note) in the public view."""
        import re
        declared = set()
        for line in public_puml.splitlines():
            m = re.match(
                r'(?:class|interface|enum|union|package|note)\s+"[^"]*"\s+as\s+(\S+)',
                line.strip(),
            )
            if m:
                declared.add(m.group(1))
        arrow_pattern = re.compile(
            r'(\S+)\s+(<\|--|\.\.\|>|\.\.>|-->|o--|\*--)\s+(\S+)\s+: '
        )
        for line in public_puml.splitlines():
            m = arrow_pattern.search(line)
            if m and m.group(3) not in declared:
                raise AssertionError(
                    f"Public-view arrow target is not a declared element "
                    f"(member alias?): {line.strip()!r}"
                )

