    # ------------------------------------------------------------------
    # Fidelity: public edges are a subset of collapsed edges
    # ------------------------------------------------------------------

    def test_public_edges_are_subset_of_collapsed(self, public_puml):
        """Every edge in the public-only view is also present in the
        collapsed view.  Hiding private members and external deps
        should only remove edges, never add new ones.

        All public-view edge targets are project-internal (no external
        packages)."""
        import re

        collapsed_path = _CODEGRAPH_OUTPUT / "cpp_sqlite_one_hop_collapsed.puml"
        collapsed_puml = collapsed_path.read_text(encoding="utf-8")

        def _parse(puml):
            edges = set()
            for L in puml.splitlines():
                m = re.match(
                    r'(\S+)\s+(<\|--|\.\.\|>|\.\.>|-->|o--|\*--)\s+(\S+)\s+:\s+(\S+)',
                    L,
                )
                if m:
                    edges.add((m.group(1), m.group(2), m.group(3), m.group(4)))
            return edges

        collapsed_edges = _parse(collapsed_puml)
        public_edges = _parse(public_puml)

        # Assert no external package targets
        external_pkgs = {"std", "boost", "spdlog", "sqlite3", "detail", "fmt", "mp_cond"}
        for _, _, tgt, _ in public_edges:
            assert tgt not in external_pkgs, (
                f"Public view edge targets external package: {tgt}"
            )

        spurious: list[tuple] = []
        for src, arrow, tgt, label in public_edges:
            if (src, arrow, tgt, label) not in collapsed_edges:
                spurious.append((src, arrow, tgt, label))

        assert len(spurious) == 0, (
            f"{len(spurious)} edges in public view not present in collapsed:\n"
            + "\n".join(
                f"  {s} {a} {t} : {l}" for s, a, t, l in spurious[:10]
            )
        )

